import Foundation
import Metal
import simd

/// `--audit-props [out.md]` (F01 W3.1): lists every scene item of both worlds with its material mix, size and whether it is drawn in the flat `standard`
/// material (a constant colour with no procedural detail). The user walks everywhere and looks at everything; the named views only showed a few objects, so
/// several large things (causeway slabs, islet pillars, rocks, pebbles) were never upgraded. This makes the omission impossible to miss.
enum PropAudit {
    struct Row {
        var world: String, name: String, triangles: Int, size: SIMD3<Float>, flatShare: Float, materials: [String: Int]
        /// A single object (not a merged batch) whose largest face would cover more than 0.5 % of a 1600x900 frame at 5 m (about 0.30 m^2).
        var largeFlat: Bool
        var merged: Bool
    }

    static func materialName(_ id: Int) -> String {
        ["standard", "terrain", "emissiveGlass", "foliage", "bird", "masonry", "paint", "iron", "copper", "wood", "bark", "dressed", "plank", "timber", "glyphStone",
         "paper", "pebble", "glassStone", "mirror", "paleMetal", "glyphGlass", "rock", "slab"][min(max(id, 0), 22)]
    }

    static func rows(scenes: [WorldKind: Scene]) -> [Row] {
        var out: [Row] = []
        for (kind, scene) in scenes.sorted(by: { $0.key.rawValue < $1.key.rawValue }) {
            for item in scene.items {
                let n = item.mesh.vertexBuffer.length / MemoryLayout<Vertex>.stride
                let verts = item.mesh.vertexBuffer.contents().bindMemory(to: Vertex.self, capacity: n)
                var counts: [Int: Int] = [:]
                for i in 0..<n { counts[Int(verts[i].normal.w + 0.5), default: 0] += 1 }
                let flat = Float(counts[0] ?? 0) / Float(max(n, 1))
                let ext = item.mesh.boundsMax - item.mesh.boundsMin
                let sorted = [ext.x, ext.y, ext.z].sorted(by: >)
                let merged = sorted[0] > 25 || item.name.hasPrefix("litter") || item.name.contains("_L1_") || item.name.contains("_L2_")
                let glowing = item.uniforms.emissive.w > 0.5 || item.refractive
                let isTerrain = (counts[1] ?? 0) > n / 2
                out.append(Row(world: kind.rawValue, name: item.name, triangles: item.mesh.indexCount / 3, size: ext, flatShare: flat,
                               materials: Dictionary(uniqueKeysWithValues: counts.map { (materialName($0.key), $0.value) }),
                               largeFlat: !merged && !glowing && !isTerrain && flat > 0.6 && sorted[0] * sorted[1] > 0.30, merged: merged))
            }
        }
        return out
    }

    static func markdown(_ rows: [Row]) -> String {
        var s = "# Prop coverage audit\n\nGenerated by `Lanternwright --audit-props docs/PROPS.md` (F01 W3.1). `flat` = share of vertices in the constant-colour `standard` material. "
        s += "A **large flat** prop is a single object (not a merged batch) whose biggest face is over 0.30 m^2 (0.5 % of a 1600x900 frame at 5 m) and is drawn flat: treat each as a defect.\n\n"
        let flagged = rows.filter(\.largeFlat)
        s += "## Large flat props: \(flagged.count)\n\n"
        for r in flagged { s += "- `\(r.world)/\(r.name)`: \(r.triangles) triangles, \(fmt(r.size)) m, flat \(Int(r.flatShare * 100)) %\n" }
        let flatBatches = rows.filter { $0.merged && $0.flatShare > 0.6 && !$0.name.hasPrefix("gw_lamps") && !$0.name.hasPrefix("lantern_cores") && !$0.name.contains("_L1_") && !$0.name.contains("_L2_") && !$0.name.hasPrefix("crystals") }
        s += "\n## Merged batches drawn mostly flat: \(flatBatches.count)\n\n"
        for r in flatBatches { s += "- `\(r.world)/\(r.name)`: \(r.triangles) triangles, flat \(Int(r.flatShare * 100)) %\n" }
        s += "\n## Every item\n\n| world | item | triangles | size (m) | flat | materials |\n|---|---|---|---|---|---|\n"
        for r in rows {
            let mats = r.materials.sorted { $0.value > $1.value }.prefix(4).map { "\($0.key) \($0.value)" }.joined(separator: ", ")
            s += "| \(r.world) | `\(r.name)` | \(r.triangles) | \(fmt(r.size)) | \(Int(r.flatShare * 100)) % | \(mats) |\n"
        }
        return s
    }
    private static func fmt(_ v: SIMD3<Float>) -> String { String(format: "%.1f x %.1f x %.1f", v.x, v.y, v.z) }

    static func run(renderer: Renderer, out: String?) throws {
        let rows = rows(scenes: renderer.scenes)
        let md = markdown(rows)
        if let out { try md.write(toFile: out, atomically: true, encoding: .utf8); print("wrote \(out)") }
        print(md.components(separatedBy: "\n## Every item").first ?? "")
    }
}
