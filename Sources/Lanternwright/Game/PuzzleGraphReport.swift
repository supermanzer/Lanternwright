/// P02.0: `--puzzle-graph [out.md]` prints (and optionally writes) the tables of `docs/plans/P02-graph-report.md` from the live game, so the reviewer can regenerate them after any change.
/// The report file keeps its hand-written text outside the markers; `--puzzle-graph docs/plans/P02-graph-report.md` replaces only what lies between `<!-- graph:begin -->` and `<!-- graph:end -->`.
enum PuzzleGraphReport {
    static let begin = "<!-- graph:begin -->", end = "<!-- graph:end -->"

    static func today(device: MTLDevice) -> PuzzleGraph {
        let scenes: [WorldKind: Scene] = [.varrow: Scene.make(.varrow, device: device), .glassWood: Scene.make(.glassWood, device: device), .tideArchive: Scene.make(.tideArchive, device: device)]
        return PuzzleGraph.today(game: Game(scenes: scenes))
    }

    private static func world(_ w: WorldKind) -> String { w.rawValue }
    private static func clueText(_ c: PuzzleClue, in n: PuzzleNode, _ g: PuzzleGraph) -> String {
        let d = PuzzleRules.distance(c, to: n, in: g)
        let far = d.map { $0.isInfinite ? "another world" : String(format: "%.0f m", $0) } ?? "no machine position"
        return "\(c.label) (\(far))"
    }

    static func markdown(_ g: PuzzleGraph) -> String {
        var o: [String] = []
        let breaks = PuzzleRules.breaks(g)

        o.append("### The graph (generated by `--puzzle-graph`, from the live game)")
        o.append("")
        o.append("Kinds: puzzle (counted), story (a beat with no datum), transit (moving between worlds). `opt` = optional, never counted as open. Answers are glyph tokens; `man.` is the fewest manipulations, computed (the mirror court by searching its 1728 settings, rings by their steps).")
        o.append("")
        o.append("| id | world | kind | verb / channel | answer | man. | needs | sets | clues (distance from machine) |")
        o.append("|---|---|---|---|---|---|---|---|---|")
        for n in g.puzzles {
            o.append("| \(n.id)\(n.optional ? " (opt)" : "")\(n.group.map { " [\($0)]" } ?? "")\(n.route.map { " <\($0.rawValue)>" } ?? "")\(n.planned != nil ? " **(planned)**" : "") | \(world(n.world)) | \(n.kind.rawValue) | \(n.verb) / \(n.channel.rawValue) | \(n.answer.isEmpty ? "-" : n.answer.joined(separator: ", ")) | \(n.manipulations == 0 ? "-" : String(n.manipulations)) | \(n.requires.isEmpty ? "-" : n.requires.joined(separator: ", ")) | \(n.sets ?? "-") | \(n.clues.isEmpty ? "none" : n.clues.map { clueText($0, in: n, g) }.joined(separator: "; ")) |")
        }

        o.append("")
        o.append("### Feedback each machine gives (declared from the code; the cell names the event)")
        o.append("")
        o.append("| puzzle | sense | kind | within | what the player sees or hears |")
        o.append("|---|---|---|---|---|")
        for n in g.puzzles where !n.feedback.isEmpty { for f in n.feedback { o.append("| \(n.id) | \(f.sense.rawValue) | \(f.kind.rawValue) | \(String(format: "%.2f s", f.seconds)) | \(f.note) |") } }

        o.append("")
        o.append("### Pages that state the order in words (read from the page text, both voices)")
        o.append("")
        o.append("| page | world | consumers (puzzles that list it as a clue) |")
        o.append("|---|---|---|")
        for p in g.pages where p.statesOrder {
            let users = g.puzzles.filter { $0.clues.contains { $0.source == .page(p.id) } }.map(\.id)
            o.append("| \(p.id) | \(world(p.world)) | \(users.isEmpty ? "**none**" : users.joined(separator: ", ")) |")
        }

        o.append("")
        o.append("### Keys: what the player carries between places (P02 section 3.2; `built` = both ends exist in the game, `planted` = an unflagged datum no page states)")
        o.append("")
        o.append("| key | channel | learned at | used at (puzzles that list it as a clue) | built? | the datum |")
        o.append("|---|---|---|---|---|---|")
        for k in g.keys {
            let status: String
            switch k.status { case .built: status = k.planted ? "built, planted" : "built"; case .planned(let who): status = "planned: \(who)" }
            let users = k.usedAt.isEmpty ? "-" : k.usedAt.map { u in (g.node(u)?.clues.contains { $0.source == .key(k.id) } ?? false) ? u : "\(u) (**does not list it**)" }.joined(separator: ", ")
            o.append("| \(k.id) | \(k.channel.rawValue) | \(k.learnedAt) (\(world(k.learnedWorld))) | \(users) | \(status) | \(k.value) |")
        }

        o.append("")
        o.append("### What is open when the player chooses (a player who always takes the first open puzzle; the Archive once per route: `<ilse>` / `<oren>` mark a puzzle that is one sibling's)")
        o.append("")
        o.append("| route | step | solves | world | open at that moment | verdict |")
        o.append("|---|---|---|---|---|---|")
        let routes = Set(g.puzzles.compactMap(\.route)).sorted { $0.rawValue < $1.rawValue }
        for r in routes.isEmpty ? [nil] : routes.map({ Optional($0) }) {
        let steps = PuzzleRules.timeline(g, route: r)
        for (i, s) in steps.enumerated() {
            o.append("| \(r?.rawValue ?? "all") | \(i + 1) | \(s.id) | \(world(s.world)) | \(s.open.joined(separator: ", ")) | \(s.firstInWorld ? "first of its world (exempt)" : (i == steps.count - 1 ? "the last puzzle (exempt)" : (s.open.count >= PuzzleRules.minOpen ? "ok" : "**only \(s.open.count)**"))) |")
        }
        }

        o.append("")
        o.append("### Rule breaks (\(breaks.count))")
        o.append("")
        o.append("| rule | what it asks | subject | found |")
        o.append("|---|---|---|---|")
        let titles = Dictionary(uniqueKeysWithValues: PuzzleRules.ruleTitles)
        for b in breaks { o.append("| \(b.rule) | \(titles[b.rule] ?? "") | \(b.subject) | \(b.detail) |") }
        o.append("")
        o.append("Rules with no break: " + PuzzleRules.ruleTitles.map(\.0).filter { r in !breaks.contains { $0.rule == r } }.joined(separator: ", "))
        return o.joined(separator: "\n")
    }

    static func main(device: MTLDevice, out: String?) -> Bool {
        let g = today(device: device)
        let text = markdown(g)
        guard let out else { print(text); return true }
        if let existing = try? String(contentsOfFile: out, encoding: .utf8), let a = existing.range(of: begin), let b = existing.range(of: end) {
            let merged = existing.replacingCharacters(in: a.upperBound..<b.lowerBound, with: "\n" + text + "\n")
            try? merged.write(toFile: out, atomically: true, encoding: .utf8)
            print("updated the generated block of \(out) (\(PuzzleRules.breaks(g).count) rule breaks)")
        } else {
            try? text.write(toFile: out, atomically: true, encoding: .utf8)
            print("wrote \(out) (\(PuzzleRules.breaks(g).count) rule breaks)")
        }
        return true
    }
}
